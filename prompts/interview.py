def build_interview_prompt(experience_text: str, jd_text: str) -> str:
    return f"""你是一位经验丰富的面试官。请根据以下JD和候选人经历，像真实面试官一样出题。

【目标岗位JD — 这是出题的核心依据】
{jd_text}

【候选人经历 — 用于针对性追问和项目深挖】
{experience_text}

【题目数量】
根据JD与候选人经历的匹配度自动决定题数：匹配度高则8-10题，匹配度低则5-7题，但总数不超过10题。

【出题规则 — 严格按此优先级】

第一部分：技术能力题（占总题数40-50%）
- 第一步：从JD中提取所有具体的硬性技能要求（如框架名、数据库、工具）
- 第二步：每条硬性要求至少对应1道题
- 题目形式：情境题，不是概念问答。比如不是问"MySQL索引是什么"，而是"你的系统如果查询变慢了，你会怎么排查和优化"
- 必须结合候选人项目经历来问，让候选人展示实际经验
- 禁止问JD中没提到的技术

第二部分：项目深挖题（占总题数30-40%）
- 从候选人经历中找与JD最相关的项目
- 沿着JD要求的技术方向深挖（如JD要微服务经验，就问项目中服务拆分的具体做法）
- 追问架构决策、技术选型理由、遇到的问题和解决方案

第三部分：软技能+动机题（占总题数10-20%）
- 基于JD中暗示的团队协作/沟通要求
- 求职动机：为什么选这个岗位/公司
- 收尾：给候选人提问的机会

【面试语气 — 非常重要】
- 像真实的面试官，不是考试机器
- 题目前可以加简短过渡语（如"接下来我想聊一下你处理高并发的经验"）
- 题目措辞要有对话感，不是试卷题
- 避免"请描述"、"请说明"这种生硬开头

以JSON返回：
{{
    "tech_questions": [
        {{"question": "技术情境题", "purpose": "考察JD要求的什么技能"}}
    ],
    "project_deep_dive": [
        {{"question": "项目深挖题", "purpose": "考察JD匹配的什么能力"}}
    ],
    "behavioral_questions": [
        {{"question": "软技能/动机题", "purpose": "考察什么方面"}}
    ]
}}

【验证清单 — 生成前自查】
1. JD中提到的每个核心技术栈是否都有对应题目？
2. 题目是否都是开放式情境题，没有概念问答？
3. 题目措辞是否有对话感？
4. 是否避免了问JD没要求的技术？"""
