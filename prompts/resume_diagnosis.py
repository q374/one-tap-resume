def build_diagnosis_prompt(resume_html: str, jd_text: str = "") -> str:
    """找茬模式：以挑剔 HR 视角找出会淘汰这份简历的具体问题，不给总分"""
    jd_block = jd_text.strip() or "（未提供 JD，请基于通用简历标准判断）"
    return f"""你是一位极其挑剔、有十年招聘经验的HR，专门负责简历初筛。你的任务是找出**所有会让你直接淘汰这份简历的硬伤**。

【求职者投递的JD（用于对照）】
{jd_block}

【简历HTML】
{resume_html}

【你的角色】
- 你非常挑剔，倾向淘汰，不轻易给好评
- 你只挑毛病，不给总分、不给鼓励
- 每条问题必须具体到"哪个位置 + 什么硬伤 + 会被淘汰的原因 + 怎么改"
- 如果简历确实没什么大问题，就如实说"无明显硬伤"，但列出仍可提升的1-2点

以JSON返回，不要任何解释：
{{
    "suggestions": [
        {{"area": "问题区域（如 项目经历-第2个 / 专业技能）", "issue": "具体硬伤（20-40字）", "fix": "可落地的修改建议（20-40字）"}}
    ]
}}

要求：
- 只输出 3-5 条最致命、会直接导致被筛掉的问题
- 重点检查：量化成果是否缺失、与JD是否错位（JD要的技能简历有没有体现）、学历/年限是否满足、是否有明显AI味、是否超过一页、硬性要求是否写全
- 禁止输出"整体还不错"这类客套话"""
